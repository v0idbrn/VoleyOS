export function translateOutputKey(key: string, locale: Locale): string | null {
  const hit = OUTPUT_KEY_LABELS[key];
  return hit ? pick(locale, hit) : null;
}

export function translateEnum(value: string, locale: Locale): string {
  const hit = ENUM_LABELS[value];
  if (hit) return pick(locale, hit);
  if (/^[A-Z][A-Z0-9_]+$/.test(value)) {
    // Last resort: never leak an engine constant (SOME_STATUS) into the UI.
    const words = value.toLowerCase().split("_").join(" ");
    return words.charAt(0).toUpperCase() + words.slice(1);
  }
  return value;
}

export function translateInputLabel(key: string, locale: Locale): string {
  const hit = INPUT_LABELS[key];
  if (hit) return pick(locale, hit);
  const human = key
    .replace(/_/g, " ")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/^./, (char) => char.toUpperCase());
  return human;
}

export function humanizeKey(key: string): string {
  return key
    .replace(/_/g, " ")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/^./, (char) => char.toUpperCase());
}
